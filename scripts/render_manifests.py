#!/usr/bin/env python3
"""Regenerate the Homebrew formula and Scoop manifest for a release.

Reads the checksums in ``dist/SHA256SUMS`` and writes all four manifests
from scratch. Generating rather than patching is deliberate: the real tap
drifted into a state where ``version``, ``url`` and ``sha256`` disagreed
with each other, which is only possible when each field is edited by hand.

Env:
  VERSION             release version, no leading "v"
  GITHUB_REPOSITORY   "<owner>/<repo>", supplied by GitHub Actions
"""

import json
import os
import pathlib
import sys

# Appended to the SAS-variant URLs. Mimics the shape of an Azure Blob
# read-only SAS so we can find out whether Homebrew and Scoop still infer
# the download filename correctly when a query string is present. The
# values are inert padding, not a credential.
SAS_QUERY = (
    "?sv=2024-11-04&ss=b&srt=o&sp=r&se=2030-01-01T00:00:00Z"
    "&st=2026-01-01T00:00:00Z&spr=https&sig=" + "A" * 43 + "%3D"
)

ROOT = pathlib.Path(__file__).resolve().parent.parent


def checksums(path):
    """Parse ``<sha256>  <filename>`` lines into {filename: sha256}."""
    out = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            out[parts[1]] = parts[0]
    return out


def formula(klass, version, repo, assets, sums, query=""):
    base = f"https://github.com/{repo}/releases/download/v{version}"

    def block(key, indent):
        name = assets[key]
        pad = " " * indent
        return (
            f'{pad}url "{base}/{name}{query}"\n'
            f'{pad}sha256 "{sums[name]}"'
        )

    note = ""
    if query:
        note = (
            "#\n"
            "# SAS-URL spike: identical to cx.rb except the download URLs carry a\n"
            "# query string, to establish whether Homebrew still infers the archive\n"
            "# filename correctly. See docs/SAS_SPIKE.md.\n"
        )

    return f"""# typed: false
# frozen_string_literal: true

# Generated by scripts/render_manifests.py -- do not edit by hand.
#
# Distribution-rehearsal formula. The binary it installs is a stand-in with
# no product functionality; see the repository README.
{note}
class {klass} < Formula
  desc "Distribution rehearsal stand-in for the Commerce+ eXtensibility Toolkit CLI"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{block('darwin-arm64', 6)}
    end
    on_intel do
{block('darwin-x86_64', 6)}
    end
  end

  on_linux do
    on_intel do
{block('linux-x86_64', 6)}
    end
  end

  def install
    bin.install "cx"
  end

  test do
    assert_match "cx", shell_output("#{{bin}}/cx --help")
    assert_match version.to_s, shell_output("#{{bin}}/cx --version")
  end
end
"""


def scoop(version, repo, assets, sums, query=""):
    base = f"https://github.com/{repo}/releases/download/v{version}"
    name = assets["windows-x86_64"]
    manifest = {
        "version": version,
        "description": (
            "Distribution rehearsal stand-in for the Commerce+ eXtensibility "
            "Toolkit CLI (no product functionality)"
        ),
        "homepage": f"https://github.com/{repo}",
        "license": "MIT",
        "architecture": {
            "64bit": {"url": f"{base}/{name}{query}", "hash": sums[name]}
        },
        "bin": "cx.exe",
        "checkver": {"github": f"https://github.com/{repo}"},
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": (
                        f"https://github.com/{repo}/releases/download/v$version"
                        f"/cx-v$version-windows-x86_64.zip{query}"
                    )
                }
            },
            "hash": {
                "url": (
                    f"https://github.com/{repo}/releases/download/"
                    "v$version/SHA256SUMS"
                ),
                "regex": r"$sha256\s+cx-v$version-windows-x86_64\.zip",
            },
        },
    }
    return json.dumps(manifest, indent=4) + "\n"


def main():
    version = os.environ.get("VERSION", "").strip().lstrip("v")
    repo = os.environ.get("GITHUB_REPOSITORY", "").strip()
    if not version or not repo:
        sys.exit("VERSION and GITHUB_REPOSITORY must both be set")

    sums = checksums(ROOT / "dist" / "SHA256SUMS")
    assets = {
        k: f"cx-v{version}-{k}.{'zip' if k.startswith('windows') else 'tar.gz'}"
        for k in ("darwin-arm64", "darwin-x86_64", "linux-x86_64", "windows-x86_64")
    }

    missing = [n for n in assets.values() if n not in sums]
    if missing:
        sys.exit("missing from SHA256SUMS: " + ", ".join(missing))

    written = {
        "Formula/cx.rb": formula("Cx", version, repo, assets, sums),
        "Formula/cx-sas.rb": formula(
            "CxSas", version, repo, assets, sums, SAS_QUERY
        ),
        "bucket/cx.json": scoop(version, repo, assets, sums),
        "bucket/cx-sas.json": scoop(version, repo, assets, sums, SAS_QUERY),
    }
    for rel, body in written.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        print(f"wrote {rel}")


if __name__ == "__main__":
    main()
